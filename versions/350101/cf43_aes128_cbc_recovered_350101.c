static uint8_t xtime(uint8_t x) {
    return (uint8_t)((x << 1) ^ ((x & 0x80) ? 0x1b : 0x00));
}

static void aes128_key_expand(const uint8_t key[16], uint8_t round_key[176]) {
    memcpy(round_key, key, 16);
    int bytes = 16;
    int rcon_i = 0;
    uint8_t t[4];

    while (bytes < 176) {
        memcpy(t, round_key + bytes - 4, 4);
        if ((bytes % 16) == 0) {
            uint8_t tmp = t[0];
            t[0] = (uint8_t)(sbox[t[1]] ^ rcon[rcon_i++]);
            t[1] = sbox[t[2]];
            t[2] = sbox[t[3]];
            t[3] = sbox[tmp];
        }
        for (int i = 0; i < 4; i++) {
            round_key[bytes] = (uint8_t)(round_key[bytes - 16] ^ t[i]);
            bytes++;
        }
    }
}

static void add_round_key(uint8_t st[16], const uint8_t *rk) {
    for (int i = 0; i < 16; i++) {
        st[i] ^= rk[i];
    }
}

static void sub_bytes(uint8_t st[16]) {
    for (int i = 0; i < 16; i++) {
        st[i] = sbox[st[i]];
    }
}

static void shift_rows(uint8_t st[16]) {
    uint8_t t[16];
    t[0]  = st[0];  t[1]  = st[5];  t[2]  = st[10]; t[3]  = st[15];
    t[4]  = st[4];  t[5]  = st[9];  t[6]  = st[14]; t[7]  = st[3];
    t[8]  = st[8];  t[9]  = st[13]; t[10] = st[2];  t[11] = st[7];
    t[12] = st[12]; t[13] = st[1];  t[14] = st[6];  t[15] = st[11];
    memcpy(st, t, 16);
}

static void mix_columns(uint8_t st[16]) {
    for (int c = 0; c < 4; c++) {
        uint8_t *a = st + c * 4;
        uint8_t t = (uint8_t)(a[0] ^ a[1] ^ a[2] ^ a[3]);
        uint8_t u = a[0];
        a[0] ^= (uint8_t)(t ^ xtime((uint8_t)(a[0] ^ a[1])));
        a[1] ^= (uint8_t)(t ^ xtime((uint8_t)(a[1] ^ a[2])));
        a[2] ^= (uint8_t)(t ^ xtime((uint8_t)(a[2] ^ a[3])));
        a[3] ^= (uint8_t)(t ^ xtime((uint8_t)(a[3] ^ u)));
    }
}

static void aes128_encrypt_block(const uint8_t in[16], uint8_t out[16], const uint8_t rk[176]) {
    uint8_t st[16];
    memcpy(st, in, 16);
    add_round_key(st, rk);

    for (int round = 1; round <= 9; round++) {
        sub_bytes(st);
        shift_rows(st);
        mix_columns(st);
        add_round_key(st, rk + round * 16);
    }

    sub_bytes(st);
    shift_rows(st);
    add_round_key(st, rk + 160);
    memcpy(out, st, 16);
}

static size_t pkcs7_pad16(uint8_t *out, size_t out_cap, const uint8_t *in, size_t in_len) {
    size_t pad = 16 - (in_len & 15);
    size_t out_len = in_len + pad;
    if (out_len > out_cap) {
        return 0;
    }
    memcpy(out, in, in_len);
    memset(out + in_len, (int)pad, pad);
    return out_len;
}

static void aes128_cbc_encrypt(uint8_t *out, const uint8_t *in, size_t len,
                               const uint8_t key[16], const uint8_t iv[16]) {
    uint8_t rk[176];
    uint8_t chain[16];
    uint8_t block[16];
    aes128_key_expand(key, rk);
    memcpy(chain, iv, 16);

    for (size_t off = 0; off < len; off += 16) {
        for (int i = 0; i < 16; i++) {
            block[i] = (uint8_t)(in[off + i] ^ chain[i]);
        }
        aes128_encrypt_block(block, chain, rk);
        memcpy(out + off, chain, 16);
    }
}

size_t metasec_cf43_aes128_cbc_pkcs7_encrypt_350101(uint8_t *out,
                                                     size_t out_cap,
                                                     const uint8_t *body,
                                                     size_t body_len,
                                                     const uint8_t key[16],
                                                     const uint8_t iv[16]) {
    uint8_t padded[4096];
    size_t padded_len = pkcs7_pad16(padded, sizeof(padded), body, body_len);
    if (padded_len == 0 || padded_len > out_cap) {
        return 0;
    }
    aes128_cbc_encrypt(out, padded, padded_len, key, iv);
    return padded_len;
}

static void dump_mismatch(const char *name, const uint8_t *got, const uint8_t *want, size_t len) {
    for (size_t i = 0; i < len; i++) {
        if (got[i] != want[i]) {
            printf("%s mismatch at +0x%zx: got=%02x want=%02x\n", name, i, got[i], want[i]);
            return;
        }
    }
}

